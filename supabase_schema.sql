-- Chạy toàn bộ file này một lần trong Supabase -> SQL Editor.
-- Bot backend dùng SUPABASE_SECRET_KEY (khuyên dùng) hoặc legacy service_role key.

create table if not exists public.bot_users (
    telegram_id bigint primary key,
    username text,
    first_name text,
    last_name text,
    language_code text,
    created_at timestamptz not null default now(),
    last_active_at timestamptz not null default now()
);

create table if not exists public.bot_user_state (
    telegram_user_id bigint primary key references public.bot_users(telegram_id) on delete cascade,
    state jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.bot_files (
    id bigint generated by default as identity primary key,
    telegram_user_id bigint references public.bot_users(telegram_id) on delete set null,
    storage_chat_id bigint not null,
    storage_message_id bigint not null,
    telegram_file_id text,
    telegram_file_unique_id text,
    file_name text,
    mime_type text,
    file_type text not null,
    file_size bigint,
    source_chat_id bigint,
    source_message_id bigint,
    created_at timestamptz not null default now(),
    unique (storage_chat_id, storage_message_id)
);

create index if not exists idx_bot_files_user_created
    on public.bot_files (telegram_user_id, created_at desc);

create table if not exists public.bot_updates (
    update_id bigint primary key,
    status text not null default 'processing' check (status in ('processing', 'done', 'failed')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Backend secret/service_role key bypasses RLS. Keep public clients locked out.
alter table public.bot_users enable row level security;
alter table public.bot_user_state enable row level security;
alter table public.bot_files enable row level security;
alter table public.bot_updates enable row level security;

grant all on table public.bot_users to service_role;
grant all on table public.bot_user_state to service_role;
grant all on table public.bot_files to service_role;
grant all on table public.bot_updates to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Gateway: mọi người dùng chat riêng và nhấn /start đều được đăng ký nhận thông báo.
create table if not exists public.bot_alert_subscribers (
    telegram_id bigint primary key references public.bot_users(telegram_id) on delete cascade,
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);

-- Gateway: chống gửi trùng khi client cung cấp event_id.
create table if not exists public.bot_gateway_events (
    source text not null,
    event_id text not null,
    status text not null default 'processing'
        check (status in ('processing', 'done', 'partial')),
    sent integer not null default 0,
    failed integer not null default 0,
    blocked integer not null default 0,
    created_at timestamptz not null default now(),
    finished_at timestamptz,
    primary key (source, event_id)
);

alter table public.bot_alert_subscribers enable row level security;
alter table public.bot_gateway_events enable row level security;
grant all on table public.bot_alert_subscribers to service_role;
grant all on table public.bot_gateway_events to service_role;

-- Cho phép người dùng đã /start trước khi nâng cấp cũng nhận cảnh báo.
insert into public.bot_alert_subscribers (telegram_id, enabled)
select s.telegram_user_id, true
from public.bot_user_state s
where s.state ->> 'started' = 'true'
on conflict (telegram_id) do nothing;

-- PHASE 1: private signed uploads (existing bot tables remain unchanged).
-- Create Storage bucket `telegram-gateway-temp` in Supabase Dashboard > Storage,
-- with PUBLIC OFF and file size limit 50 MB (Free plan may enforce 50 MB).
create table if not exists public.bot_gateway_uploads (
    id uuid primary key,
    source text not null,
    event_id text,
    object_path text not null unique,
    filename text not null,
    media_type text not null check (media_type in ('photo','video','document','audio','voice','animation')),
    file_size bigint not null check (file_size > 0 and file_size <= 49000000),
    message text not null default 'Tệp đính kèm',
    title text,
    level text not null default 'info' check (level in ('info','warning','critical')),
    status text not null default 'pending' check (status in ('pending','processing','done','partial','failed')),
    telegram_file_id text,
    storage_message_id bigint,
    sent integer not null default 0,
    failed integer not null default 0,
    blocked integer not null default 0,
    temp_deleted boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create unique index if not exists idx_bot_gateway_uploads_event
    on public.bot_gateway_uploads (source,event_id) where event_id is not null;
create index if not exists idx_bot_gateway_uploads_cleanup
    on public.bot_gateway_uploads (created_at) where temp_deleted=false;
alter table public.bot_gateway_uploads enable row level security;
grant all on table public.bot_gateway_uploads to service_role;
